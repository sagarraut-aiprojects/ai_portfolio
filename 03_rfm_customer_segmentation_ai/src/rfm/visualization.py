import matplotlib.pyplot as plt
from sklearn.decomposition import PCA



def plot_segment_customers(segment_summary, output_path=None):
    """
    Plot the number of customers in each RFM segment.

    Parameters
    ----------
    segment_summary : pandas.DataFrame
        Segment-level summary statistics.
    output_path : str, optional
        Path to save the figure.
    """

    plt.figure(figsize=(9, 5))

    plt.bar(
        segment_summary["Segment"],
        segment_summary["Customers"],
    )

    plt.title("Customers by RFM Segment")
    plt.xlabel("Customer Segment")
    plt.ylabel("Number of Customers")

    plt.xticks(rotation=20)
    plt.tight_layout()

    if output_path:
        plt.savefig(output_path, dpi=300)

    plt.show()


